"""Generate the runtime's trusted tensor inventory from tracked model checksums."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / 'third_party/mochizuki'
SOURCE = VENDOR / 'linux/package/model-tools'
DEST = VENDOR / 'windows/src/core/nr_model_profile.hpp'


def main():
    lines = ['// Generated by tools/mochizuki-sync/generate-model-profile.py.',
             '#pragma once', 'namespace nr::model_profile {',
             'struct Tensor { const char* name; const char* sha256; };']
    for family, suffix, count in (('original', '', 599), ('small', '-small', 255)):
        entries = []
        for row in (SOURCE / f'model-files{suffix}.sha256').read_text(encoding='utf-8').splitlines():
            if row.strip():
                digest, name = row.split(None, 1)
                if not re.fullmatch('[0-9a-f]{64}', digest):
                    raise ValueError('Invalid tensor checksum')
                entries.append((name.strip(), digest))
        if len(entries) != count or len({name for name, _ in entries}) != count:
            raise ValueError(f'Invalid {family} tensor inventory')
        lines.append(f'inline constexpr Tensor {family}_tensors[] = {{')
        lines.extend(f'    {{{json.dumps(name)}, "{digest}"}},' for name, digest in entries)
        lines.append('};')
    lines.extend(['} // namespace nr::model_profile', ''])
    DEST.write_text('\n'.join(lines), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
