"""Generate the runtime allowlist from the pinned upstream model manifest."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
DEST=ROOT/'OptiScaler-DLSSNR-PreSR-Multipass-main/OptiScaler/dlssnr/backend/lmxxf_runtime/LmxxfSmallAssets.h'

def render():
    manifest=json.loads((ROOT/'tools/install/lmxxf-small-manifest.json').read_text(encoding='utf-8-sig'))
    rows=['#pragma once', '// Generated by tools/dev/generate-lmxxf-small-header.py; no model coefficients.',
          'struct LmxxfSmallAsset { const wchar_t* name; unsigned bytes; const char* sha256; };',
          'inline constexpr LmxxfSmallAsset kLmxxfSmallAssets[] = {']
    for name,item in manifest['files'].items():
        rows.append('    { L"%s", %d, "%s" },' % (name,item['bytes'],item['sha256']))
    return '\n'.join(rows+['};',''])

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    result=render()
    if args.check:
        if DEST.read_text(encoding='utf-8-sig') != result: raise SystemExit('Small asset allowlist is stale')
    else:DEST.write_text(result,encoding='utf-8')
